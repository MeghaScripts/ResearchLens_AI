"""
Report export (Word .docx + Markdown .md).

The PDF report is still produced by generate_pdf_report() /
generate_multi_pdf_report() in app.py. This module renders the SAME content
(single-paper or multi-paper analysis) into two more formats so the
"Download Report" button can offer a Word / PDF / Markdown menu, and so the
Markdown file can be imported into Notion and the Word file into Google Docs.

Design: build_blocks() turns the analysis dict into a small, format-neutral
list of blocks; to_markdown() and to_docx() just render those blocks. That
keeps all three exports consistent and means a new section only has to be
added once.

Block kinds:
    ('title', text)        ('meta', text)          ('h1', text)
    ('h2', text)           ('p', text)             ('kv', [(label, value), ...])
    ('ol', [text, ...])    ('scores', [(label, value), ...])
"""
import datetime
import io
import re


def _s(value, default=''):
    """Coerce anything the LLM returned into clean text."""
    if value is None:
        return default
    if isinstance(value, (list, tuple)):
        return ', '.join(str(v) for v in value if v)
    return str(value).strip() or default


def build_blocks(topic, analysis, papers, mode=None):
    analysis = analysis or {}
    papers = papers or []
    multi = (mode == 'multi') or bool(analysis.get('literature_review'))
    now = datetime.datetime.now().strftime('%B %d, %Y at %H:%M')
    b = []

    b.append(('title', 'Multi-Paper Research Gap Analysis Report' if multi
              else 'Research Gap Analysis Report'))
    b.append(('meta', f"Topic: {_s(topic, 'N/A')}"))
    b.append(('meta', f"Papers Analyzed: {len(papers)} | Generated: {now}"))

    if multi:
        lit = analysis.get('literature_review') or {}
        b.append(('h1', 'Literature Review'))
        for label, key in [('Introduction', 'introduction'), ('Main Findings', 'main_findings'),
                           ('Methodologies Used', 'methodologies'), ('Limitations', 'limitations'),
                           ('Conclusion', 'conclusion')]:
            if _s(lit.get(key)):
                b.append(('h2', label))
                b.append(('p', _s(lit.get(key))))

        summaries = analysis.get('paper_summaries') or []
        if summaries:
            b.append(('h1', 'Individual Paper Summaries'))
            for ps in summaries:
                b.append(('h2', _s(ps.get('paper_name'), 'Paper')))
                b.append(('kv', [
                    ('Objective', _s(ps.get('objective'))),
                    ('Methodology', _s(ps.get('methodology'))),
                    ('Dataset', _s(ps.get('dataset'), 'N/A')),
                    ('Key Results', _s(ps.get('key_results'))),
                    ('Limitations', _s(ps.get('limitations'))),
                ]))
    else:
        b.append(('h1', 'Executive Summary'))
        b.append(('p', _s(analysis.get('summary'))))
        b.append(('scores', [
            ('Novelty Score', f"{_s(analysis.get('novelty_score'), 'N/A')}/100"),
            ('Gap Density', _s(analysis.get('gap_density'), 'N/A').upper()),
            ('Papers Analyzed', str(len(papers))),
        ]))
        if _s(analysis.get('overall_recommendation')):
            b.append(('h2', 'Overall Recommendation'))
            b.append(('p', _s(analysis.get('overall_recommendation'))))

    gaps = analysis.get('research_gaps') or []
    b.append(('h1', 'Identified Research Gaps & Evidence'))
    if not gaps:
        b.append(('p', 'No research gaps were identified.'))
    for i, gap in enumerate(gaps, 1):
        sev = _s(gap.get('severity'), 'moderate')
        b.append(('h2', f"Gap #{i}: {_s(gap.get('gap_title'))}"))
        b.append(('kv', [
            ('Severity', f"{sev.upper()} | Confidence: {_s(gap.get('confidence_score'), 'N/A')}%"),
            ('Description', _s(gap.get('description'))),
            ('Why Important', _s(gap.get('why_important'))),
            ('Suggested Approach', _s(gap.get('suggested_approach'))),
            ('Expected Impact', _s(gap.get('estimated_impact'))),
            ('Evidence Papers', _s(gap.get('evidence_papers'))),
            ('Gap Proof', _s(gap.get('evidence_explanation'))),
        ]))

    steps = [_s(x) for x in (analysis.get('recommended_next_steps') or []) if _s(x)]
    if steps:
        b.append(('h1', 'Recommended Next Steps'))
        b.append(('ol', steps))

    if not multi and papers:
        b.append(('h1', 'Related Papers Found'))
        lines = []
        for p in papers[:10]:
            authors = ', '.join((p.get('authors') or [])[:2])
            lines.append(f"{_s(p.get('title'))} ({_s(p.get('year'))}) — {authors}")
        b.append(('ol', lines))

    b.append(('meta', 'Generated by ResearchLens AI • Autonomous Research Gap Detection System'))
    return b


# ── Markdown ─────────────────────────────────────────────────────────
def _md_escape_cell(text):
    # Keep multi-line / pipe-containing text safe inside a Markdown table cell.
    return re.sub(r'\s*\n\s*', ' ', text).replace('|', '\\|')


def to_markdown(blocks):
    out = []
    for kind, val in blocks:
        if kind == 'title':
            out.append(f"# {val}\n")
        elif kind == 'meta':
            out.append(f"*{val}*  ")
        elif kind == 'h1':
            out.append(f"\n## {val}\n")
        elif kind == 'h2':
            out.append(f"\n### {val}\n")
        elif kind == 'p':
            out.append(f"{val}\n")
        elif kind == 'scores':
            out.append('| ' + ' | '.join(l for l, _ in val) + ' |')
            out.append('|' + '---|' * len(val))
            out.append('| ' + ' | '.join(_md_escape_cell(v) for _, v in val) + ' |\n')
        elif kind == 'kv':
            out.append('| Field | Details |')
            out.append('|---|---|')
            for label, v in val:
                out.append(f"| **{label}** | {_md_escape_cell(v)} |")
            out.append('')
        elif kind == 'ol':
            out.extend(f"{i}. {t}" for i, t in enumerate(val, 1))
            out.append('')
    return '\n'.join(out).strip() + '\n'


# ── Word (.docx) ─────────────────────────────────────────────────────
def to_docx(blocks):
    from docx import Document
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor, Inches

    doc = Document()
    sec = doc.sections[0]
    sec.left_margin = sec.right_margin = Inches(0.9)
    sec.top_margin = sec.bottom_margin = Inches(0.8)

    normal = doc.styles['Normal']
    normal.font.name = 'Calibri'
    normal.font.size = Pt(10.5)
    for name, size, color in [('Heading 1', 15, '16213E'), ('Heading 2', 12.5, '0F3460')]:
        st = doc.styles[name]
        st.font.name = 'Calibri'
        st.font.size = Pt(size)
        st.font.bold = True
        st.font.color.rgb = RGBColor.from_string(color)

    def shade(cell, hex_fill):
        tcPr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement('w:shd')
        shd.set(qn('w:val'), 'clear')
        shd.set(qn('w:color'), 'auto')
        shd.set(qn('w:fill'), hex_fill)
        tcPr.append(shd)

    def cell_text(cell, text, bold=False, color=None, center=False):
        cell.text = ''
        p = cell.paragraphs[0]
        run = p.add_run(text)
        run.bold = bold
        if color:
            run.font.color.rgb = RGBColor.from_string(color)
        if center:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    for kind, val in blocks:
        if kind == 'title':
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(val)
            r.bold = True
            r.font.size = Pt(22)
            r.font.color.rgb = RGBColor.from_string('1A1A2E')
        elif kind == 'meta':
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(val)
            r.font.size = Pt(9)
            r.font.color.rgb = RGBColor.from_string('666666')
        elif kind == 'h1':
            doc.add_heading(val, level=1)
        elif kind == 'h2':
            doc.add_heading(val, level=2)
        elif kind == 'p':
            doc.add_paragraph(val)
        elif kind == 'ol':
            for t in val:
                doc.add_paragraph(t, style='List Number')
        elif kind == 'scores':
            t = doc.add_table(rows=2, cols=len(val))
            t.style = 'Table Grid'
            t.alignment = WD_TABLE_ALIGNMENT.CENTER
            for i, (label, v) in enumerate(val):
                cell_text(t.cell(0, i), label, bold=True, color='FFFFFF', center=True)
                shade(t.cell(0, i), '0F3460')
                cell_text(t.cell(1, i), v, bold=True, center=True)
                shade(t.cell(1, i), 'E8F4FD')
            doc.add_paragraph()
        elif kind == 'kv':
            t = doc.add_table(rows=len(val), cols=2)
            t.style = 'Table Grid'
            for i, (label, v) in enumerate(val):
                cell_text(t.cell(i, 0), label, bold=True)
                shade(t.cell(i, 0), 'EEF3FA')
                cell_text(t.cell(i, 1), v)
                t.cell(i, 0).width = Inches(1.6)
                t.cell(i, 1).width = Inches(5.1)
            doc.add_paragraph()

    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf